package com.nobi.appbuilder.ui.flow;

import android.view.LayoutInflater;
import android.view.View;
import android.view.ViewGroup;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.recyclerview.widget.RecyclerView;

import com.nobi.appbuilder.R;
import com.nobi.appbuilder.events.EventDefinition;

import java.util.ArrayList;
import java.util.List;

/** Lists the events bound to one component; tap to edit one. */
public class EventActionAdapter
        extends RecyclerView.Adapter<EventActionAdapter.Holder> {

    public interface OnEventClickListener {
        void onEventClick(EventDefinition definition);
    }

    private final List<EventDefinition> items = new ArrayList<>();
    private final OnEventClickListener listener;

    public EventActionAdapter(OnEventClickListener listener) {
        this.listener = listener;
    }

    public void setItems(List<EventDefinition> definitions) {
        items.clear();
        if (definitions != null) {
            items.addAll(definitions);
        }
        notifyDataSetChanged();
    }

    @NonNull
    @Override
    public Holder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
        View view = LayoutInflater.from(parent.getContext())
                .inflate(R.layout.item_event_action, parent, false);
        return new Holder(view);
    }

    @Override
    public void onBindViewHolder(@NonNull Holder holder, int position) {
        EventDefinition definition = items.get(position);
        holder.title.setText(definition.summary());
        holder.detail.setText(definition.isGeneratable()
                ? "Generated by the code generator"
                : "Workflow only — not generated");
        holder.itemView.setOnClickListener(v -> {
            if (listener != null) {
                listener.onEventClick(definition);
            }
        });
    }

    @Override
    public int getItemCount() {
        return items.size();
    }

    static class Holder extends RecyclerView.ViewHolder {
        final TextView title;
        final TextView detail;

        Holder(@NonNull View itemView) {
            super(itemView);
            title = itemView.findViewById(R.id.text_event_action_title);
            detail = itemView.findViewById(R.id.text_event_action_detail);
        }
    }
}
